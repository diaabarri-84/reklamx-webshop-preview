#!/usr/bin/env node
// Write the package.json the SERVER needs — derived from the built server, not
// from the repo's.
//
// The repo lists every front-end library under "dependencies" (react, vite,
// fabric, pdfjs…). None of them run on the server: the browser gets them
// already bundled inside dist/assets. Installing them anyway costs ~570 MB and
// a long, failure-prone install on a shared host.
//
// So the list is read out of dist/server.cjs itself — every bare require that
// esbuild left external — and pinned to the exact versions installed here.
// Derived from the artefact, it cannot drift from the code.
import { readFileSync, writeFileSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { join } from 'node:path';

const [, , releaseDir] = process.argv;
if (!releaseDir) { console.error('usage: release-manifest.mjs <release-dir>'); process.exit(1); }

const bundle = readFileSync('dist/server.cjs', 'utf8');
const builtin = new Set(builtinModules);
const names = new Set();
for (const [, id] of bundle.matchAll(/require\(["']([^"']+)["']\)/g)) {
  if (id.startsWith('.') || id.startsWith('/')) continue;
  const bare = id.startsWith('node:') ? id.slice(5) : id;
  const top = bare.startsWith('@') ? bare.split('/').slice(0, 2).join('/') : bare.split('/')[0];
  if (builtin.has(top)) continue;
  names.add(top);
}

const repo = JSON.parse(readFileSync('package.json', 'utf8'));
const deps = {};
for (const name of [...names].sort()) {
  // The version actually installed and tested here, exactly — not a range that
  // could resolve to something else on the server months from now.
  const installed = JSON.parse(readFileSync(join('node_modules', name, 'package.json'), 'utf8'));
  deps[name] = installed.version;
  if (!repo.dependencies?.[name] && !repo.devDependencies?.[name]) {
    console.error(`✗ ${name} is required by the server but is in neither dependency list.`);
    process.exit(1);
  }
}

writeFileSync(join(releaseDir, 'package.json'), JSON.stringify({
  name: 'reklamx-shop',
  version: repo.version || '1.0.0',
  private: true,
  description: 'Runtime manifest for the built shop. Generated by scripts/release-manifest.mjs — do not edit by hand.',
  scripts: { start: 'node dist/server.cjs' },
  dependencies: deps,
}, null, 2) + '\n');

console.log(`  runtime packages: ${Object.keys(deps).join(', ')}`);
